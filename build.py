#!/usr/bin/env python3
"""Build the self-contained OPNsense installer archive."""
from pathlib import Path
import argparse
import base64
import io
import tarfile

ROOT = Path(__file__).resolve().parent
PKG = ROOT / "pkg"


def build(output: Path, one_file: bool) -> Path:
    output.parent.mkdir(parents=True, exist_ok=True)
    with tarfile.open(output, "w:gz") as tar:
        # The release is commonly built on Windows. A developer or tool may
        # have written CRLF into a text file despite the repository's LF
        # attributes; on FreeBSD that breaks executable shebangs (for example,
        # Python sees `/usr/local/bin/python3\r`). Canonicalize text in the
        # archive so packaging is independent of the builder's OS and
        # working-tree line endings.
        paths = [PKG, *sorted(PKG.rglob("*")), ROOT / "README.md"]
        for path in paths:
            if path == PKG or PKG in path.parents:
                arcname = Path("pkg") / path.relative_to(PKG)
            else:
                arcname = Path("README.md")
            info = tar.gettarinfo(str(path), arcname=str(arcname).replace("\\", "/"))
            if path.is_file():
                data = path.read_bytes()
                if b"\0" not in data:
                    data = data.replace(b"\r\n", b"\n")
                info.size = len(data)
                tar.addfile(info, io.BytesIO(data))
            else:
                tar.addfile(info)

    if not one_file:
        return output

    installer = output.with_suffix(".sh")
    payload = base64.b64encode(output.read_bytes()).decode("ascii")
    lines = "\n".join(payload[i:i + 76] for i in range(0, len(payload), 76))
    installer.write_text(
        "#!/bin/sh\n"
        "# Self-contained installer generated by build.py.\n"
        "set -e\n"
        'TMP=$(mktemp -d)\n'
        'awk "/^__PAYLOAD_B64__$/{f=1;next} f" "$0" | base64 -d > "$TMP/pkg.tar.gz"\n'
        'tar -xzf "$TMP/pkg.tar.gz" -C "$TMP"\n'
        'sh "$TMP/pkg/install.sh"\n'
        "RC=$?\n"
        'rm -rf "$TMP"\n'
        "exit $RC\n"
        "__PAYLOAD_B64__\n" + lines + "\n",
        encoding="utf-8",
        newline="\n",
    )
    return installer


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=ROOT / "dist/opnsense-openconnect.tar.gz")
    parser.add_argument("--one-file", action="store_true", help="also generate a self-contained .sh installer")
    args = parser.parse_args()
    if build(args.output, args.one_file):
        print(f"built: {args.output}")
        if args.one_file:
            print(f"built: {args.output.with_suffix('.sh')}")


if __name__ == "__main__":
    main()

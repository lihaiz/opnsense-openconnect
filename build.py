#!/usr/bin/env python3
"""Build the self-contained OPNsense installer archive."""
from pathlib import Path
import argparse
import base64
import tarfile

ROOT = Path(__file__).resolve().parent
PKG = ROOT / "pkg"


def build(output: Path, one_file: bool) -> Path:
    output.parent.mkdir(parents=True, exist_ok=True)
    with tarfile.open(output, "w:gz") as tar:
        tar.add(PKG, arcname="pkg")
        tar.add(ROOT / "README.md", arcname="README.md")

    if not one_file:
        return output

    installer = output.with_suffix(".sh")
    payload = base64.b64encode(output.read_bytes()).decode("ascii")
    lines = "\n".join(payload[i:i + 76] for i in range(0, len(payload), 76))
    installer.write_text(
        "#!/bin/sh\n"
        "# Self-contained installer generated by build.py.\n"
        "set -e\n"
        'TMP=$(mktemp -d)\n'
        'awk "/^__PAYLOAD_B64__$/{f=1;next} f" "$0" | base64 -d > "$TMP/pkg.tar.gz"\n'
        'tar -xzf "$TMP/pkg.tar.gz" -C "$TMP"\n'
        'sh "$TMP/pkg/install.sh"\n'
        "RC=$?\n"
        'rm -rf "$TMP"\n'
        "exit $RC\n"
        "__PAYLOAD_B64__\n" + lines + "\n",
        encoding="utf-8",
        newline="\n",
    )
    return installer


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=ROOT / "dist/opnsense-openconnect.tar.gz")
    parser.add_argument("--one-file", action="store_true", help="also generate a self-contained .sh installer")
    args = parser.parse_args()
    if build(args.output, args.one_file):
        print(f"built: {args.output}")
        if args.one_file:
            print(f"built: {args.output.with_suffix('.sh')}")


if __name__ == "__main__":
    main()
